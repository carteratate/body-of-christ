"""Where each Catechism paragraph is printed in the USCCB flipbook.

The Catechism is excerpt-only (issue #265), so its passages link to the USCCB's online
edition, a FlippingBook flipbook. Its viewer opens any page at `<base>/<page>/index.html`,
so a passage links to the page where its first paragraph starts instead of the cover.
catechism_pages.json holds that page for every paragraph; it is generated by
scripts/build_catechism_pages.py, which reads the flipbook's page images and checks every
number against our text.

The table holds for one publication of the flipbook, named by its GUID. If the USCCB
republishes it, the pages may move: the API checks the live GUID at most once a day, in
the background, and on a mismatch links every passage to the cover again until the table
is rebuilt. A failed check changes nothing.
"""
from __future__ import annotations

import asyncio
import json
import logging
import re
import time
from functools import lru_cache
from pathlib import Path

import httpx

logger = logging.getLogger(__name__)

FLIPBOOK = "https://www.usccb.org/sites/default/files/flipbooks/catechism"
COVER_URL = f"{FLIPBOOK}/index.html"

_SOURCE = Path(__file__).with_name("catechism_pages.json")
# A Catechism passage's unit label is its first paragraph ("§1127"); see
# datapipeline/ingest/catechism.py.
_UNIT_LABEL = re.compile(r"§(\d{1,4})")
_GUID = re.compile(r'GUID\s*=\s*"([0-9a-f]{32})"')
_CHECK_EVERY_SECONDS = 24 * 3600
_CHECK_TIMEOUT_SECONDS = 5.0


@lru_cache(maxsize=1)
def _table() -> dict:
    return json.loads(_SOURCE.read_text())


class _Publication:
    """What the last GUID check found. `republished` stays False until a check succeeds
    and disagrees with the table."""

    def __init__(self) -> None:
        self.republished = False
        self.checked_at: float | None = None
        self.task: asyncio.Task | None = None


_publication = _Publication()


def page_url(unit_label: str | None) -> str | None:
    """The flipbook page where a Catechism passage's first paragraph starts, or None
    when the label names no paragraph in the table or the flipbook was republished."""
    match = _UNIT_LABEL.fullmatch(unit_label or "")
    if not match:
        return None
    _schedule_check()
    if _publication.republished:
        return None
    table = _table()
    page = table["flipbook_page"].get(match.group(1))
    if page is None:
        return None
    # The viewer numbers pages from the flipbook index less the publication's offset.
    return f"{FLIPBOOK}/{page - table['numeration_offset']}/index.html"


def _schedule_check() -> None:
    state = _publication
    if state.task is not None and not state.task.done():
        return
    if state.checked_at is not None and time.monotonic() - state.checked_at < _CHECK_EVERY_SECONDS:
        return
    try:
        state.task = asyncio.get_running_loop().create_task(check_publication())
    except RuntimeError:
        pass  # no event loop (a script or a sync test): links use the table as built


async def check_publication(client: httpx.AsyncClient | None = None) -> bool | None:
    """Compare the live flipbook's GUID with the table's. True when it matches, False
    when the flipbook was republished, None when the check could not be made."""
    _publication.checked_at = time.monotonic()
    try:
        if client is None:
            async with httpx.AsyncClient(timeout=_CHECK_TIMEOUT_SECONDS) as own:
                response = await own.get(COVER_URL)
        else:
            response = await client.get(COVER_URL)
        response.raise_for_status()
    except httpx.HTTPError as exc:
        logger.warning("catechism flipbook check failed (%s); keeping page links",
                       exc.__class__.__name__)
        return None
    found = _GUID.search(response.text)
    if not found:
        logger.warning("catechism flipbook check: no GUID on the page; keeping page links")
        return None
    same = found.group(1) == _table()["guid"]
    if not same and not _publication.republished:
        logger.warning(
            "catechism flipbook republished (guid %s, table built for %s); passages link "
            "to the cover until scripts/build_catechism_pages.py is rerun",
            found.group(1), _table()["guid"])
    _publication.republished = not same
    return same
